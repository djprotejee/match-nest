def list_entity_records() -> dict[str, EntityRecord]:
    connection = connect()
    try:
        rows = connection.execute("SELECT * FROM entities ORDER BY sport, kind, name").fetchall()
        alias_rows = connection.execute("SELECT entity_id, alias FROM entity_aliases ORDER BY alias").fetchall()
        binding_rows = connection.execute(
            "SELECT entity_id, provider, binding_type, binding_value, metadata_json FROM entity_provider_bindings ORDER BY provider, binding_type"
        ).fetchall()
    finally:
        connection.close()

    aliases: dict[str, list[str]] = {}
    for row in alias_rows:
        aliases.setdefault(row["entity_id"], []).append(row["alias"])
    bindings: dict[str, list[EntityBinding]] = {}
    for row in binding_rows:
        bindings.setdefault(row["entity_id"], []).append(
            EntityBinding(
                provider=row["provider"],
                binding_type=row["binding_type"],
                value=row["binding_value"],
                metadata=json.loads(row["metadata_json"] or "{}"),
            )
        )
    return {
        row["id"]: EntityRecord(
            entity=Entity(row["id"], row["name"], Sport(row["sport"]), EntityKind(row["kind"]), row["color"]),
            aliases=aliases.get(row["id"], []),
            bindings=bindings.get(row["id"], []),
            is_seed=bool(row["is_seed"]),
            created_by_user_id=row["created_by_user_id"],
        )
        for row in rows
    }


def get_entity_record(entity_id: str) -> EntityRecord | None:
    return list_entity_records().get(entity_id)


def create_custom_entity(
    user_id: int,
    name: str,
    sport: Sport,
    kind: EntityKind,
    color: str,
    level: str,
    aliases: Iterable[str] = (),
    bindings: Iterable[EntityBinding] = (),
) -> EntityRecord:
    entity_id = slugify_entity_id(name)
    existing = list_entity_records()
    base_id = entity_id
    suffix = 2
    while entity_id in existing:
        entity_id = f"{base_id}_{suffix}"
        suffix += 1

    now = utc_now().isoformat()
    connection = connect()
    try:
        connection.execute(
            """
            INSERT INTO entities (id, name, sport, kind, color, is_seed, created_by_user_id, created_at, updated_at)
            VALUES (?, ?, ?, ?, ?, 0, ?, ?, ?)
            """,
            (entity_id, name.strip(), sport.value, kind.value, color, user_id, now, now),
        )
        upsert_entity_aliases(connection, entity_id, aliases)
        upsert_entity_bindings(connection, entity_id, bindings)
        connection.commit()
    finally:
        connection.close()
    set_user_follow(user_id, Follow(entity_id, level))
    record = get_entity_record(entity_id)
    if record is None:
        raise RuntimeError("Created entity could not be loaded.")
    return record


def update_custom_entity(
    user_id: int,
    entity_id: str,
    name: str,
    sport: Sport,
    kind: EntityKind,
    color: str,
    aliases: Iterable[str],
    bindings: Iterable[EntityBinding],
) -> EntityRecord:
    connection = connect()
    try:
        row = connection.execute("SELECT * FROM entities WHERE id = ?", (entity_id,)).fetchone()
        if not row:
            raise ValueError("Entity not found.")
        if bool(row["is_seed"]) or row["created_by_user_id"] != user_id:
            raise PermissionError("Only your custom entities can be edited.")
        connection.execute(
            """
            UPDATE entities
            SET name = ?, sport = ?, kind = ?, color = ?, updated_at = ?
            WHERE id = ?
            """,
            (name.strip(), sport.value, kind.value, color, utc_now().isoformat(), entity_id),
        )
        connection.execute("DELETE FROM entity_aliases WHERE entity_id = ?", (entity_id,))
        connection.execute("DELETE FROM entity_provider_bindings WHERE entity_id = ?", (entity_id,))
        upsert_entity_aliases(connection, entity_id, aliases)
        upsert_entity_bindings(connection, entity_id, bindings)
        connection.commit()
    finally:
        connection.close()
    record = get_entity_record(entity_id)
    if record is None:
        raise RuntimeError("Updated entity could not be loaded.")
    return record


