def search_entity_records(query: str) -> list[EntityRecord]:
    text = normalize_search(query)
    if not text:
        return []
    records = list_entity_records().values()
    return [
        record
        for record in records
        if text in normalize_search(record.entity.name)
        or any(text in normalize_search(alias) for alias in record.aliases)
    ]


def provider_bindings_for(provider: str, binding_type: str | None = None) -> dict[str, list[str]]:
    output: dict[str, list[str]] = {}
    for entity_id, record in list_entity_records().items():
        for binding in record.bindings:
            if binding.provider != provider:
                continue
            if binding_type is not None and binding.binding_type != binding_type:
                continue
            output.setdefault(entity_id, []).append(binding.value)
    return output


