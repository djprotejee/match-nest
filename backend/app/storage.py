def slugify_entity_id(value: str) -> str:
    output = []
    for char in value.lower().strip():
        if char.isalnum():
            output.append(char)
        elif output and output[-1] != "_":
            output.append("_")
    slug = "".join(output).strip("_")
    return slug or f"entity_{secrets.token_hex(4)}"


