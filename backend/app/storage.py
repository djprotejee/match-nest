def get_or_create_oauth_user(provider: str, subject: str, email: str) -> UserAccount:
    normalized = normalize_email(email)
    now = utc_now()
    connection = connect()
    try:
        row = connection.execute(
            """
            SELECT users.* FROM oauth_accounts
            JOIN users ON users.id = oauth_accounts.user_id
            WHERE oauth_accounts.provider = ? AND oauth_accounts.subject = ?
            """,
            (provider, subject),
        ).fetchone()
        if row:
            return user_from_row(row)

        user_row = connection.execute("SELECT * FROM users WHERE email = ?", (normalized,)).fetchone()
        if user_row:
            user_id = int(user_row["id"])
        else:
            cursor = connection.execute(
                """
                INSERT INTO users (email, password_hash, email_verified_at, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                (normalized, "oauth", now.isoformat(), now.isoformat(), now.isoformat()),
            )
            user_id = int(cursor.lastrowid)
            initialize_user_preferences(connection, user_id)

        connection.execute(
            """
            INSERT INTO oauth_accounts (provider, subject, user_id, email, created_at, updated_at)
            VALUES (?, ?, ?, ?, ?, ?)
            """,
            (provider, subject, user_id, normalized, now.isoformat(), now.isoformat()),
        )
        connection.commit()
        user = get_user_by_id_with_connection(connection, user_id)
        if user is None:
            raise RuntimeError("OAuth user could not be loaded.")
        return user
    finally:
        connection.close()


