def consume_oauth_state(provider: str, raw_state: str) -> bool:
    state_hash = hash_token(raw_state)
    connection = connect()
    try:
        row = connection.execute(
            """
            SELECT 1 FROM oauth_states
            WHERE state_hash = ? AND provider = ? AND expires_at >= ?
            """,
            (state_hash, provider, utc_now().isoformat()),
        ).fetchone()
        connection.execute("DELETE FROM oauth_states WHERE state_hash = ?", (state_hash,))
        connection.commit()
        return row is not None
    finally:
        connection.close()


