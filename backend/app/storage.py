class PostgresCursor:
    """Small cursor adapter that keeps the storage layer compatible with sqlite3."""

    def __init__(self, cursor: Any, lastrowid: int | None = None) -> None:
        self.cursor = cursor
        self.lastrowid = lastrowid

    def fetchone(self) -> dict[str, Any] | None:
        return self.cursor.fetchone()

    def fetchall(self) -> list[dict[str, Any]]:
        return list(self.cursor.fetchall())


class PostgresConnection:
    """Translate the limited SQLite SQL used by MatchNest to Postgres."""

    def __init__(self, database_url: str) -> None:
        if psycopg is None or dict_row is None:
            raise RuntimeError("DATABASE_URL is set, but psycopg is not installed.")
        self.connection = psycopg.connect(database_url, row_factory=dict_row)

    def execute(self, sql: str, params: Iterable[Any] = ()) -> PostgresCursor:
        translated, wants_lastrowid = translate_sql_for_postgres(sql)
        cursor = self.connection.execute(translated, tuple(params))
        lastrowid = None
        if wants_lastrowid:
            row = cursor.fetchone()
            lastrowid = int(row["id"]) if row else None
        return PostgresCursor(cursor, lastrowid)

    def commit(self) -> None:
        self.connection.commit()

    def close(self) -> None:
        self.connection.close()


def connect() -> sqlite3.Connection | PostgresConnection:
    database_url = os.getenv(DATABASE_URL_ENV, "").strip()
    if database_url:
        connection = PostgresConnection(database_url)
        ensure_db_initialized(connection, f"postgres:{database_url}", use_postgres_lock=True)
        return connection
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(DB_PATH)
    connection.row_factory = sqlite3.Row
    ensure_db_initialized(connection, f"sqlite:{DB_PATH.resolve()}", use_postgres_lock=False)
    return connection


def ensure_db_initialized(
    connection: sqlite3.Connection | PostgresConnection,
    database_key: str,
    use_postgres_lock: bool,
) -> None:
    if database_key in _INITIALIZED_DATABASES:
        return
    with _INIT_LOCK:
        if database_key in _INITIALIZED_DATABASES:
            return
        if use_postgres_lock:
            connection.execute("SELECT pg_advisory_lock(?)", (POSTGRES_INIT_LOCK_KEY,))
        try:
            init_db(connection)
            _INITIALIZED_DATABASES.add(database_key)
        finally:
            if use_postgres_lock:
                connection.execute("SELECT pg_advisory_unlock(?)", (POSTGRES_INIT_LOCK_KEY,))
                connection.commit()


def translate_sql_for_postgres(sql: str) -> tuple[str, bool]:
    translated = sql.strip()
    insert_or_ignore = "INSERT OR IGNORE INTO" in translated
    translated = translated.replace(
        "id INTEGER PRIMARY KEY AUTOINCREMENT",
        "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )
    translated = translated.replace("INSERT OR IGNORE INTO", "INSERT INTO")
    translated = translated.replace("?", "%s")

    wants_lastrowid = translated.upper().startswith("INSERT INTO USERS ") and "RETURNING" not in translated.upper()
    if wants_lastrowid:
        translated += " RETURNING id"
    elif insert_or_ignore and "ON CONFLICT" not in translated.upper():
        translated += " ON CONFLICT DO NOTHING"
    return translated, wants_lastrowid


